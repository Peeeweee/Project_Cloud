// Builds src/sketch-colors.css: the sketchbook recolor of every stylesheet the deck imports.
//
// Each color declaration is copied under `html.sketch`, which raises every selector by the same
// amount, so the original cascade order between rules is kept. Colors written for the dark slides
// are flipped onto paper (dark backgrounds become paper, light text becomes ink, orange accents
// become a deeper pencil orange). Rules written for the light "paper" slides keep their colors.
//
// Run after changing any stylesheet:  node tools/sketch-theme.mjs
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const main = fs.readFileSync(path.join(root, 'src/main.js'), 'utf8');
const files = [...main.matchAll(/^import '\.\/([\w-]+\.css)';/gm)].map(m => m[1])
  .filter(f => !f.startsWith('sketch'));

const COLOR = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\b(?:white|black)\b/g;
const PAPER_CONTEXT = /tone-paper|tone-split/;

function parse(c) {
  if (c === 'white') return [255, 255, 255, 1];
  if (c === 'black') return [0, 0, 0, 1];
  if (c[0] === '#') {
    let h = c.slice(1);
    if (h.length <= 4) h = [...h].map(x => x + x).join('');
    const n = [0, 2, 4, 6].map(i => parseInt(h.slice(i, i + 2) || 'ff', 16));
    return [n[0], n[1], n[2], n[3] / 255];
  }
  const p = c.replace(/rgba?\(|\)/g, '').split(/[\s,/]+/).filter(Boolean).map(Number);
  return [p[0], p[1], p[2], p.length > 3 ? p[3] : 1];
}
function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > .5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function fromHsl(h, s, l) {
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map(v => Math.round(v * 255));
}
const out = ([r, g, b], a) => a >= .999
  ? '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('')
  : `rgba(${r},${g},${b},${+a.toFixed(3)})`;

// Dark-slide color -> paper-slide color.
function flip(c) {
  const rgba = parse(c), [h, s, l] = toHsl(rgba), a = rgba[3];
  const warm = h <= 55 || h >= 330;
  if (s >= .42 && l >= .22 && l <= .8) {
    // accents: orange and rust become pencil orange / brick; other hues keep their hue, deepened
    if (warm) return out(l > .66 ? [199, 90, 30] : l < .4 ? [166, 54, 30] : [217, 84, 30], a);
    return out(fromHsl(h, Math.min(s, .7), Math.min(l, .5)), a);
  }
  // everything else flips its lightness, so contrast with the page is kept: dark surfaces become
  // paper, light text becomes ink, a faint line stays a faint line. Grays take the paper's warm hue.
  const nl = Math.min(.975, Math.max(.11, 1 - l));
  const hh = s < .15 ? (nl > .5 ? 22 : 330) : h;
  const ss = s < .15 ? (nl > .5 ? .55 : .09) : Math.min(s, nl > .5 ? .55 : .35);
  return out(fromHsl(hh, ss, nl), a);
}

// Flipped rules apply only while the current slide is not already a paper slide; paper slides
// keep their original colors, which were designed for a light page. Full-screen overlays (chapter
// cards, panels) were dark on every slide, so they are always flipped.
const ON_DARK = 'html.sketch body:not(.tone-paper)';
const ALWAYS = /chapter-|dialog|chrome-toggle|phone-nav/;
function prefix(sel) {
  const scope = ALWAYS.test(sel) ? 'html.sketch body' : ON_DARK;
  return sel.split(',').flatMap(s => {
    s = s.trim();
    if (s.startsWith(':root')) return ['html.sketch' + s.slice(5)];
    if (s.startsWith('html')) return ['html.sketch' + s.slice(4)];
    if (/^body\b/.test(s)) return [scope + s.slice(4)];
    // a leading class may sit on <body> itself (.view-horizon, .tone-rust, .presenting ...)
    return /^[.:\[]/.test(s) ? [scope + ' ' + s, scope + s] : [scope + ' ' + s];
  }).join(',');
}

let css = `/* GENERATED by tools/sketch-theme.mjs from ${files.length} stylesheets. Do not edit by hand. */\n`;
let count = 0;
for (const file of files) {
  const tree = postcss.parse(fs.readFileSync(path.join(root, 'src', file), 'utf8'));
  const result = postcss.root();
  tree.walkRules(rule => {
    if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    const decls = [];
    rule.each(d => {
      if (d.type !== 'decl' || !COLOR.test(d.value)) return;
      COLOR.lastIndex = 0;
      if (/url\(/.test(d.value) && !/gradient/.test(d.value)) return;
      decls.push(d);
    });
    COLOR.lastIndex = 0;
    if (!decls.length) return;
    // rules written for paper slides are left alone (they never apply to a dark slide)
    const selector = rule.selectors.filter(x => !PAPER_CONTEXT.test(x)).join(',');
    if (!selector) return;
    const copy = postcss.rule({ selector: prefix(selector) });
    for (const d of decls) {
      const value = d.value.replace(COLOR, flip);
      copy.append(postcss.decl({ prop: d.prop, value, important: d.important }));
    }
    // keep the rule inside the same @media / @supports wrappers
    let node = copy;
    for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) {
      const wrap = postcss.atRule({ name: p.name, params: p.params }); wrap.append(node); node = wrap;
    }
    result.append(node); count++;
  });
  css += `\n/* ${file} */\n` + result.toString() + '\n';
}
fs.writeFileSync(path.join(root, 'src/sketch-colors.css'), css);
console.log(`sketch-colors.css: ${count} rules from ${files.join(', ')}`);
